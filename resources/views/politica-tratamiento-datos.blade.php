                        <h2 class="hero-subheading hero-subheading-dark"><span>20.</span>Cookies y tecnologías similares</h2>
                        <div class="divider-m"></div>
                        <div class="txt">
                            <p>LUPE LEGAL usa cookies y tecnologías similares esenciales para el funcionamiento, la autenticación y la seguridad, y, solo con consentimiento, de analítica. El usuario puede gestionarlas desde su navegador o desde el panel de preferencias. Estas tecnologías pueden recolectar IP, identificadores y datos de navegación.</p>
                        </div>
                    </div>
                </div>
                <div class="divider-l"></div>

                {{-- 21 --}}
                <div class="row policy-section" id="seccion-21">
                    <div class="col-lg-12">
                        <h2 class="hero-subheading hero-subheading-dark"><span>21.</span>Gobernanza y responsabilidad demostrada</h2>
                        <div class="divider-m"></div>
                        <div class="txt">
                            <p>LUPE LEGAL mantiene un Programa Integral de Gestión de Datos Personales conforme a la guía de responsabilidad demostrada de la SIC, que incluye:</p>
                            <ul>
                                <li>Designación de un responsable o oficial de protección de datos: Lorena Thalia Conde Ramírez, Oficial de protección de datos, quien atiende consultas, reclamos y supervisa el cumplimiento.</li>
                                <li>Inventario de bases de datos y mapa de flujos de datos, y su registro en el Registro Nacional de Bases de Datos (RNBD) de la SIC cuando LUPE LEGAL o el Empleador estén obligados (Decreto 090 de 2018: sociedades y entidades sin ánimo de lucro con activos totales superiores a 100.000 UVT, y personas jurídicas de naturaleza pública). Si no aplica la obligación, LUPE LEGAL mantiene el inventario internamente. El Empleador es responsable de su propio registro.</li>
                                <li>Manual interno de políticas y procedimientos (artículo 17, literal k) de la Ley 1581 de 2012), registro de autorizaciones y atención de derechos.</li>
                                <li>Evaluaciones de impacto de privacidad y análisis de riesgos, en especial para biometría e IA.</li>
                                <li>Capacitación periódica del personal y auditorías internas o externas.</li>
                                <li>Contratos con Empleadores y proveedores con cláusulas de protección de datos.</li>
                                <li>Revisión anual de esta Política o ante cambios normativos.</li>
                            </ul>
                        </div>
                    </div>
                </div>
                <div class="divider-l"></div>

                {{-- 22 --}}
                <div class="row policy-section" id="seccion-22">
                    <div class="col-lg-12">
                        <h2 class="hero-subheading hero-subheading-dark"><span>22.</span>Obligaciones del Usuario Empleador frente a LUPE LEGAL</h2>
                        <div class="divider-m"></div>
                        <div class="txt">
                            <p>Como condición para usar la plataforma, el Empleador se obliga, entre otras cosas, a:</p>
                            <ul>
                                <li>Contar con la autorización o la base legal para tratar los datos de sus Trabajadores y para transmitirlos a LUPE LEGAL, y informar al Trabajador del uso de LUPE LEGAL, de la verificación biométrica y de esta Política.</li>
                                <li>Garantizar el debido proceso y el derecho de defensa del Trabajador (Constitución art. 29; CST art. 115) y ofrecer alternativas si este no autoriza el dato sensible.</li>
                                <li>Usar la plataforma únicamente para finalidades lícitas y proporcionales, y no incluir datos sensibles o excesivos no indispensables para el proceso.</li>
                                <li>Mantener la confidencialidad y seguridad de las credenciales y de la información descargada de la plataforma, y limitar el acceso al personal que lo requiera.</li>
                                <li>Atender los derechos de los titulares y colaborar con LUPE LEGAL para su ejercicio.</li>
                                <li>Adoptar sus propias políticas de tratamiento y, si corresponde, inscribir sus bases de datos en el RNBD.</li>
                                <li>Reportar sin demora a LUPE LEGAL cualquier incidente que afecte los datos.</li>
                                <li>Tomar las decisiones disciplinarias por sí mismo, mediante personas naturales, y verificar los resultados de los agentes de IA.</li>
                            </ul>
                        </div>
                    </div>
                </div>
                <div class="divider-l"></div>

