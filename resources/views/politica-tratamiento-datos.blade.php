                                <li>No cargar contenido ilícito, malicioso o que vulnere derechos de terceros.</li>
                                <li>Informar a LUPE LEGAL o al Empleador sobre inexactitudes o accesos no autorizados.</li>
                            </ul>
                            <p>El Trabajador es responsable de la exactitud de lo que declara y de los datos de terceros que decida incluir en sus respuestas, sin perjuicio de su derecho de defensa.</p>
