                <div class="divider-l"></div>

                {{-- 17 --}}
                <div class="row policy-section" id="seccion-17">
                    <div class="col-lg-12">
                        <h2 class="hero-subheading hero-subheading-dark"><span>17.</span>Gestión de incidentes de seguridad</h2>
                        <div class="divider-m"></div>
                        <div class="txt">
                            <p>LUPE LEGAL cuenta con un procedimiento de respuesta a incidentes que incluye detección, contención, análisis, mitigación y lecciones aprendidas. En caso de violación de los códigos de seguridad o pérdida, robo, acceso o uso no autorizado de información:</p>
                            <ul>
                                <li>LUPE LEGAL notificará sin demora injustificada al Empleador (Responsable) cuando actúe como Encargado.</li>
                                <li>Se reportará a la SIC a través del Registro Nacional de Bases de Datos, dentro de los quince (15) días hábiles siguientes al momento en que se detecte el incidente y se ponga en conocimiento del área encargada, conforme a la Circular Única.</li>
                                <li>Se informará a los titulares afectados cuando el incidente pueda afectar significativamente sus derechos, con indicación de las medidas que pueden adoptar.</li>
                                <li>Se documentará el incidente, sus causas y las medidas correctivas.</li>
                            </ul>
                        </div>
                    </div>
                </div>
                <div class="divider-l"></div>

                {{-- 18 --}}
                <div class="row policy-section" id="seccion-18">
                    <div class="col-lg-12">
                        <h2 class="hero-subheading hero-subheading-dark"><span>18.</span>Conservación y supresión</h2>
                        <div class="divider-m"></div>
                        <div class="txt">
                            <p>Los datos se conservan solo durante el tiempo necesario para cumplir las finalidades descritas y los deberes legales o contractuales, y luego se suprimen, devuelven al Empleador o anonimizan de forma segura. Como referencia:</p>
                            <ul>
                                <li>Datos de cuenta del Usuario Empleador: mientras esté vigente la relación contractual y 10 años después, de conformidad con las normas que rigen el asunto.</li>
                                <li>Expediente del proceso de descargos y evidencia electrónica: durante la vigencia del contrato con el Empleador y 80 años posteriores, sin perjuicio de los plazos de prescripción de acciones laborales y de la tabla de retención documental del Empleador. LUPE LEGAL solo seguirá las instrucciones del Empleador para su devolución o supresión, siendo esta obligación cargo del usuario cliente por ostentar el vínculo laboral.</li>
                                <li>Fotografía o plantilla biométrica: 90 días desde la finalización del proceso, salvo que sea necesario conservarla como soporte probatorio de un proceso en curso o litigio, caso en el cual se conservará hasta su terminación.</li>
                                <li>Registros técnicos (logs): 3 años con fines de seguridad y prueba.</li>
                                <li>Copias de seguridad: se depuran según su ciclo de rotación, 90 días.</li>
                                <li>Datos anonimizados: sin plazo, porque ya no identifican al titular.</li>
                            </ul>
                            <p>Al terminar la relación con el Empleador, LUPE LEGAL le devolverá o exportará la información en un plazo de 60 días y la suprimirá en un plazo máximo de 30 días posteriores a la exportación, salvo deber legal de conservación.</p>
                        </div>
                    </div>
                </div>
                <div class="divider-l"></div>

                {{-- 19 --}}
                <div class="row policy-section" id="seccion-19">
                    <div class="col-lg-12">
                        <h2 class="hero-subheading hero-subheading-dark"><span>19.</span>Menores de edad</h2>
                        <div class="divider-m"></div>
                        <div class="txt">
                            <p>LUPE LEGAL no está dirigido a menores de dieciocho (18) años y no recolecta intencionalmente sus datos. Si el Empleador convocara a descargos a un trabajador menor de edad autorizado legalmente para trabajar, deberá contar con la autorización de su representante legal y garantizar el interés superior del menor y la prevalencia de sus derechos (artículo 7 de la Ley 1581 de 2012). Si LUPE LEGAL detecta datos de menores sin el sustento legal respectivo, los suprimirá.</p>
                        </div>
                    </div>
                </div>
                <div class="divider-l"></div>

