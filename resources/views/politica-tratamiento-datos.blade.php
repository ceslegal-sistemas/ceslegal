                    <div class="col-lg-12">
                        <h2 class="hero-subheading hero-subheading-dark"><span>4.</span>Definiciones</h2>
                        <div class="divider-m"></div>
                        <div class="txt">
                            <p>Las expresiones usadas tienen el significado de la Ley 1581 de 2012 y el Decreto 1074 de 2015. En particular:</p>
                            <ul>
                                <li><strong>Titular:</strong> persona natural cuyos datos son objeto de tratamiento.</li>
                                <li><strong>Dato personal:</strong> cualquier información vinculada o que pueda asociarse a una o varias personas naturales determinadas o determinables.</li>
                                <li><strong>Dato sensible:</strong> aquel que afecta la intimidad del titular o cuyo uso indebido puede generar discriminación, como los datos biométricos, de salud, afiliación sindical, origen racial o étnico, orientación sexual, convicciones políticas o religiosas.</li>
                                <li><strong>Dato biométrico:</strong> dato derivado de características físicas del titular que permite identificarlo, como los rasgos faciales de una fotografía (selfie) usada para verificar identidad.</li>
                                <li><strong>Responsable del Tratamiento:</strong> quien decide sobre la base de datos y/o el tratamiento de los datos.</li>
                                <li><strong>Encargado del Tratamiento:</strong> quien realiza el tratamiento por cuenta del Responsable.</li>
                                <li><strong>Tratamiento:</strong> cualquier operación sobre datos personales: recolección, almacenamiento, uso, circulación o supresión.</li>
                                <li><strong>Transmisión:</strong> comunicación de datos a un Encargado, dentro o fuera de Colombia, para que los trate por cuenta del Responsable.</li>
                                <li><strong>Transferencia:</strong> envío de datos por un Responsable ubicado en Colombia a un receptor que, a su vez, es Responsable, dentro o fuera del país.</li>
                                <li><strong>Autorización:</strong> consentimiento previo, expreso e informado del titular.</li>
                                <li><strong>Aviso de privacidad:</strong> comunicación verbal o escrita que informa al titular sobre la existencia de la política y las finalidades del tratamiento.</li>
                                <li><strong>Dato disociado o anonimizado:</strong> dato que, mediante técnicas adecuadas, ya no permite identificar al titular.</li>
                                <li><strong>Usuario cliente:</strong> es el cliente de LUPE LEGAL quien tiene relación laboral con el usuario empleador (el de recursos humanos y/o el que convoca los descargos) y el trabajador (el que es llamado a descargos).</li>
                                <li><strong>Usuario Empleador:</strong> persona natural designada por el Empleador (p. ej., de recursos humanos) que accede a la plataforma.</li>
                                <li><strong>Trabajador:</strong> persona natural convocada a descargos que responde el cuestionario y que tiene una relación laboral con el cliente de LUPE LEGAL.</li>
                                <li><strong>Agentes de IA:</strong> componentes de software de LUPE LEGAL basados en inteligencia artificial que asisten en las tareas descritas.</li>
                            </ul>
                        </div>
