                <div class="row policy-section" id="seccion-6">
                    <div class="col-lg-12">
                        <h2 class="hero-subheading hero-subheading-dark"><span>6.</span>Principios rectores</h2>
                        <div class="divider-m"></div>
                        <div class="txt">
                            <p>LUPE LEGAL trata los datos conforme a los principios del artículo 4 de la Ley 1581 de 2012:</p>
                            <ul>
                                <li><strong>Legalidad:</strong> el tratamiento se sujeta a la ley y a las demás disposiciones que la desarrollan.</li>
                                <li><strong>Finalidad:</strong> el tratamiento obedece a una finalidad legítima, informada al titular.</li>
                                <li><strong>Libertad:</strong> salvo las excepciones legales, solo se trata con consentimiento previo, expreso e informado.</li>
                                <li><strong>Veracidad o calidad:</strong> la información debe ser veraz, completa, exacta, actualizada, comprobable y comprensible; no se tratan datos parciales, fraccionados o que induzcan a error.</li>
                                <li><strong>Transparencia:</strong> el titular puede obtener información sobre sus datos en cualquier momento.</li>
                                <li><strong>Acceso y circulación restringida:</strong> los datos solo se comparten con personas autorizadas por el titular o la ley, y no se publican en medios de acceso masivo salvo que sean controlables.</li>
                                <li><strong>Seguridad:</strong> se adoptan medidas técnicas, humanas y administrativas para evitar adulteración, pérdida, consulta, uso o acceso no autorizado o fraudulento.</li>
                                <li><strong>Confidencialidad:</strong> quienes intervienen están obligados a reservar la información, incluso después de finalizada su relación con LUPE LEGAL.</li>
                            </ul>
                            <p>Además, LUPE LEGAL aplica como criterios de diseño la minimización de datos, la proporcionalidad, la privacidad desde el diseño y por defecto y la supervisión humana de los agentes de IA, conforme a la Circular Externa 002 de 2024 de la SIC.</p>
