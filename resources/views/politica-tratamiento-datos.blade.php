                        <h2 class="hero-subheading hero-subheading-dark"><span>16.</span>Medidas de seguridad</h2>
                        <div class="divider-m"></div>
                        <div class="txt">
                            <p>LUPE LEGAL implementa medidas técnicas, humanas y administrativas proporcionales al riesgo y a la naturaleza sensible de la información, entre ellas:</p>
                            <ol>
                                <li><strong>Cifrado y gestión de claves.</strong> La comunicación entre los usuarios y la plataforma viaja cifrada mediante HTTPS. Las contraseñas se almacenan con hash seguro (bcrypt) y nunca en texto plano. Las credenciales de integraciones con terceros se guardan cifradas, y las claves de la aplicación se gestionan a nivel de servidor, fuera del código fuente. El cifrado en reposo del resto de la información se encuentra en proceso de implementación.</li>
                                <li><strong>Control de acceso y autenticación.</strong> El acceso se otorga por roles y permisos, bajo el principio de mínimo privilegio: cada usuario accede únicamente a la información que su perfil autoriza. Los trabajadores ingresan a los portales de descargos, socialización del RIT e impugnación mediante un enlace único y personal, más un código de un solo uso enviado a su correo, con vigencia de 10 minutos y bloqueo temporal tras 3 intentos fallidos. La verificación en dos pasos para los usuarios del panel se encuentra en proceso de implementación.</li>
                                <li><strong>Segregación lógica.</strong> La información de cada empleador o bufete se mantiene aislada por cuenta mediante controles aplicados en la propia aplicación, de modo que ningún usuario puede consultar datos de otro empleador. El desarrollo y las pruebas se realizan fuera del entorno de producción.</li>
                                <li><strong>Trazabilidad e integridad.</strong> Cada aceptación del RIT genera un acta con huella digital (hash SHA-256) del texto aceptado. Se registran fecha, hora y dirección IP en los procesos de descargos, socialización del RIT e impugnación, y cada proceso disciplinario conserva una bitácora de eventos. El sellado de tiempo con tercero certificador y los registros de auditoría de alta inalterabilidad se encuentran en proceso de implementación.</li>
                                <li><strong>Protección reforzada del dato biométrico.</strong> Las fotografías de verificación se almacenan en un directorio privado, no accesible públicamente, y solo se entregan a usuarios autenticados con permiso o mediante enlaces firmados de acceso limitado. El almacenamiento independiente y cifrado de este dato se encuentra en proceso de implementación.</li>
                                <li><strong>Copias de seguridad y continuidad.</strong> LUPE Legal mantiene copias de seguridad periódicas de la información y de la aplicación, alojadas en infraestructura de un proveedor especializado, y cuenta con la capacidad de restaurar el servicio ante una falla o pérdida de datos.</li>
                                <li><strong>Gestión de vulnerabilidades.</strong> Se mantienen actualizados los componentes y dependencias de la plataforma y se aplican las correcciones de seguridad a medida que son publicadas. La realización de pruebas de seguridad periódicas se encuentra en proceso de implementación.</li>
                                <li><strong>Capacitación y confidencialidad.</strong> El personal y los contratistas con acceso a información de los empleadores están sujetos a acuerdos de confidencialidad y a instrucciones de uso adecuado de los datos personales.</li>
                                <li><strong>Políticas internas y gestión de incidentes.</strong> LUPE Legal cuenta con lineamientos internos de seguridad de la información y atiende los incidentes de seguridad conforme a la normativa de protección de datos personales aplicable. Como referencia de buenas prácticas se toman las normas ISO/IEC 27001 y 27701, sin que ello implique certificación.</li>
                            </ol>
