                        <h2 class="hero-subheading hero-subheading-dark"><span>7.</span>Datos que tratamos</h2>
                        <div class="divider-m"></div>
                        <h4 class="policy-subheading"><span class="color-switch">7.1 Datos del Usuario Empleador</span> (LUPE LEGAL como Responsable)</h4>
                        <div class="txt">
                            <ul>
                                <li><strong>Identificación y contacto:</strong> nombre, tipo y número de documento, cargo, empresa, correo corporativo y teléfono.</li>
                                <li><strong>Credenciales y cuenta:</strong> usuario, identificadores de cuenta, rol y permisos, historial de acceso.</li>
                                <li><strong>Datos de facturación y comerciales:</strong> razón social del Empleador, NIT, datos de contacto de facturación y registros contractuales.</li>
                                <li><strong>Datos de uso y trazabilidad:</strong> acciones realizadas en la plataforma (convocatorias emitidas, documentos cargados, fechas y horas), dirección IP, geolocalización aproximada derivada de la IP, dispositivo, sistema operativo, navegador, identificadores del dispositivo, metadatos de sesión y de archivos, y registros de actividad (logs).</li>
                                <li><strong>Comunicaciones:</strong> solicitudes de soporte, correos y mensajes con LUPE LEGAL.</li>
                            </ul>
                        </div>
                        <h4 class="policy-subheading"><span class="color-switch">7.2 Datos del Trabajador</span> y del proceso de descargos (LUPE LEGAL como Encargado del Empleador)</h4>
                        <div class="txt">
                            <ul>
                                <li><strong>Identificación y contacto:</strong> nombre, tipo y número de documento, correo electrónico y teléfono, cargo, área, fecha de vinculación y tipo de contrato.</li>
                                <li><strong>Datos del proceso disciplinario:</strong> fecha, hora y medio de la citación a descargos; hechos imputados; documentos y pruebas aportados por el Empleador o el Trabajador; respuestas al cuestionario; observaciones, constancias y actas; y las decisiones que el Empleador registre.</li>
                                <li><strong>Dato biométrico (sensible):</strong> fotografía o selfie capturada durante el uso del software para verificar la identidad y dejar evidencia de quién responde.</li>
                                <li><strong>Datos técnicos y de trazabilidad:</strong> dirección IP, fecha y hora (timestamp), geolocalización aproximada, dispositivo, sistema operativo, navegador, identificadores, metadatos de la sesión y de la imagen, y registros de actividad que acreditan integridad, autenticidad y no repudio.</li>
                                <li><strong>Contenido libre:</strong> cualquier información que el Trabajador decida escribir en sus respuestas, que podría incluir datos sensibles o de terceros (véase la sección 8.3).</li>
                            </ul>
                        </div>
                        <h4 class="policy-subheading"><span class="color-switch">7.3 Datos de terceros</span> referidos en el proceso</h4>
                        <div class="txt">
                            <p>Nombres, cargos y manifestaciones de testigos, quejosos u otras personas mencionadas en los hechos o documentos. Se tratan solo en la medida necesaria para el proceso y bajo la responsabilidad del Empleador.</p>
                        </div>
                        <h4 class="policy-subheading"><span class="color-switch">7.4 Datos que no pretendemos recolectar</span></h4>
                        <div class="txt">
                            <p>LUPE LEGAL no está diseñado para recolectar datos de salud, afiliación sindical, orientación sexual, creencias o datos de menores de edad. Solicitamos al Empleador y al Trabajador no incluirlos si no son indispensables para el proceso.</p>
                        </div>
